@tool
def bmi_calculator(query: str) -> str:
    """Розраховує індекс маси тіла (ІМТ/BMI).
    Використовуй коли питають ІМТ, чи вага в нормі, співвідношення ваги і зросту.
    Приклад: 'мій ІМТ, вага 75 кг, зріст 180 см'"""
    if not query.strip():
        return "Вкажи вагу (кг) та зріст (см)."
    numbers = re.findall(r"\d+(?:[.,]\d+)?", query)
    if len(numbers) < 2:
        return "Не визначено вагу та зріст. Вкажи: 'вага 75 кг, зріст 180 см'."
    weight_kg = float(numbers[0].replace(",", "."))
    height_cm = float(numbers[1].replace(",", "."))
    if weight_kg < 20 or weight_kg > 300:
        return f"Вага {weight_kg} кг виглядає некоректною."
    if height_cm < 100 or height_cm > 250:
        return f"Зріст {height_cm} см виглядає некоректним."
    bmi = weight_kg / (height_cm / 100) ** 2
    if bmi < 18.5: cat, rec = "Недостатня маса", "Збільш калорійність, додай силові."
    elif bmi < 25: cat, rec = "Норма", "Підтримуй поточний режим."
    elif bmi < 30: cat, rec = "Надмірна вага", "Збільш активність, переглянь раціон."
    else: cat, rec = "Ожиріння", "Рекомендується консультація лікаря або дієтолога та поступове коригування способу життя."
    return (f"ІМТ: {bmi:.1f}\nКатегорія: {cat}\nРекомендація: {rec}\n\n"
            "Примітка: ІМТ не враховує м'язову масу. Для спортсменів може бути неточним.")

@tool
def calorie_calculator(query: str) -> str:
    """Розраховує денну норму калорій (TDEE).
    Використовуй, коли питають про калорії, BMR,
    схуднення, набір маси або добову потребу в енергії.
    Приклад: 'вага 65 кг, зріст 168 см, 43 роки, жінка, мінімальна активність'
    """

    if not query.strip():
        return "Потрібні: вага, зріст, вік, стать і рівень активності."

    numbers = re.findall(r"\d+(?:[.,]\d+)?", query)

    if len(numbers) < 3:
        return "Не визначено параметри. Вкажи вагу, зріст і вік."

    weight_kg = float(numbers[0].replace(",", "."))
    height_cm = float(numbers[1].replace(",", "."))
    age = int(float(numbers[2].replace(",", ".")))

    q = query.lower()

    # Стать
    gender = "жінка"  # значення за замовчуванням для навчального прототипу

    if "чолов" in q or "male" in q:
        gender = "чоловік"
    elif "жін" in q or "female" in q:
        gender = "жінка"

    # Рівень активності
    activity = "помірна"

    if (
        "сид" in q
        or "комп'ютер" in q
        or "комп’ютер" in q
        or "не займа" in q
    ):
        activity = "мінімальна"
    else:
        for level in ACTIVITY_LEVELS:
            if level in q:
                activity = level
                break

    if activity is None:
        return (
            "Для розрахунку добової потреби в калоріях "
            "потрібно уточнити рівень активності: "
            "мінімальна, легка, помірна, висока або екстремальна."
        )

    bmr = calculate_bmr(weight_kg, height_cm, age, gender)
    tdee = bmr * ACTIVITY_LEVELS[activity]

    return (
        f"BMR: {bmr:.0f} ккал/день\n"
        f"TDEE ({activity} активність): {tdee:.0f} ккал/день\n\n"
        f"Підтримка ваги: {tdee:.0f} ккал\n"
        f"Схуднення: {tdee - 500:.0f} ккал\n"
        f"Набір маси: {tdee + 300:.0f} ккал\n\n"
        f"Білки: {weight_kg * 1.6:.0f}–{weight_kg * 2.2:.0f} г/день"
    )

@tool
def exercise_lookup(query: str) -> str:
    """Шукає вправи за групою м'язів (вдома або в залі).
    Використовуй коли питають вправи на конкретну групу м'язів.
    Приклад: 'вправи на груди вдома'"""
    if not query.strip():
        return f"Вкажи групу м'язів. Доступні: {', '.join(EXERCISES_DB.keys())}."
    q = query.lower()
    muscle_group = None
    for group in EXERCISES_DB:
        if group in q: muscle_group = group; break
    if not muscle_group:
        return f"Групу не розпізнано. Доступні: {', '.join(EXERCISES_DB.keys())}."
    location = "зал" if "зал" in q else "вдома"
    exercises = EXERCISES_DB[muscle_group].get(location, [])
    if not exercises:
        return f"Вправ для '{muscle_group}' ({location}) немає в базі."
    result = [f"Вправи на {muscle_group} ({location}):"]
    for ex in exercises:
        result.append(f"\n{ex['назва']} ({ex['складність']})")
        result.append(f"  Техніка: {ex['техніка']}")
        result.append(f"  Підходи: {ex['підходи']} × {ex['повторення']}")
        result.append(f"  Протипоказання: {', '.join(ex.get('протипоказання', ['не вказані']))}")
    return "\n".join(result)

